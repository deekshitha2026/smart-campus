
import db


def create_database():
    conn = db.connect()

    queries = [
        """
        CREATE TABLE IF NOT EXISTS users (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name TEXT NOT NULL,
            email TEXT UNIQUE NOT NULL,
            password TEXT NOT NULL,
            role TEXT NOT NULL DEFAULT 'student'
        )
        """,
        """
        CREATE TABLE IF NOT EXISTS subjects (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            subject_name TEXT NOT NULL,
            teacher_id INTEGER NOT NULL REFERENCES users(id),
            UNIQUE (subject_name, teacher_id)
        )
        """,
        """
        CREATE TABLE IF NOT EXISTS attendance (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            student_name TEXT NOT NULL,
            date TEXT NOT NULL,
            status TEXT NOT NULL,
            subject_id INTEGER REFERENCES subjects(id)
        )
        """,
        """
        CREATE TABLE IF NOT EXISTS activities (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            title TEXT NOT NULL,
            description TEXT NOT NULL,
            status TEXT NOT NULL,
            category TEXT NOT NULL DEFAULT 'Assignment'
        )
        """,
        """
        CREATE TABLE IF NOT EXISTS student_activities (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            student_id INTEGER NOT NULL REFERENCES users(id),
            activity_id INTEGER NOT NULL REFERENCES activities(id),
            status TEXT NOT NULL DEFAULT 'Pending',
            UNIQUE (student_id, activity_id)
        )
        """,
        """
        CREATE TABLE IF NOT EXISTS student_marks (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            student_id INTEGER NOT NULL REFERENCES users(id),
            subject TEXT NOT NULL,
            exam_name TEXT NOT NULL,
            marks_obtained REAL NOT NULL,
            max_marks REAL NOT NULL,
            teacher_id INTEGER NOT NULL REFERENCES users(id),
            UNIQUE (student_id, subject, exam_name)
        )
        """,
        """
        CREATE TABLE IF NOT EXISTS notifications (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            student_id INTEGER REFERENCES users(id),
            title TEXT NOT NULL,
            message TEXT NOT NULL,
            teacher_id INTEGER NOT NULL REFERENCES users(id),
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        )
        """,
        """
        CREATE INDEX IF NOT EXISTS idx_attendance_subject
        ON attendance(subject_id)
        """,
        """
        CREATE UNIQUE INDEX IF NOT EXISTS idx_unique_student_subject_date
        ON attendance(student_name, subject_id, date)
        WHERE subject_id IS NOT NULL
        """
    ]

    try:
        for query in queries:
            conn.execute(query)

        conn.commit()
        print("PostgreSQL database created successfully!")

    except Exception:
        conn.rollback()
        raise

    finally:
        conn.close()


if __name__ == "__main__":
    create_database()
